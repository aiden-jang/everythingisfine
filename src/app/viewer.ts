import { distanceKm } from "../geo/sphere";
import { P_WAVE_KM_PER_S, S_WAVE_KM_PER_S } from "../geo/waves";
import { MAX_KM, pathKm } from "./arrival";
import { matches } from "../data/filter";
import type { Store } from "../data/store";
import type { Filters, Quake } from "../data/types";

/*
 * The nearest one to where the reader is, roughly.
 *
 * Everything else on this screen is about the planet. This is the one line that is about them, and it is
 * the difference between four hundred dots and "the closest was 310 km from Sydney".
 *
 * **Nothing is asked and nothing leaves the browser.** The only input is
 * `Intl.DateTimeFormat().resolvedOptions().timeZone`, which every page can already read without a prompt.
 * No geolocation dialog, no IP service, no key, no request of any kind - the same constraint every feed
 * in this app is under. The zone is looked up in a table that shipped with the bundle.
 *
 * **It names the city, never the reader, and that is the whole design.** A timezone is a region, often a
 * huge one: `Asia/Shanghai` covers all of China, so a reader in Kashgar is three thousand kilometres from
 * the coordinate on that row. "310 km from you" would be a confident claim about a person derived from a
 * value that only ever described a reference point. "310 km from Shanghai" is true for every reader of
 * that zone, and for most of them it is still the city they are in.
 *
 * So the sentence is about a place the app can name honestly, and the reader supplies the last step
 * themselves. That is the same move `arrival.ts` makes when it quotes the agency's own "38 km NW of
 * Stanton, Texas" rather than measuring to a city of its own choosing.
 */

/**
 * `[lon, lat]`, as generated by `tools/make-zones.mjs` from tzdb.
 *
 * Typed as a plain array rather than a pair, because that is what parsed JSON is: nothing in the type
 * system reaches into the file to promise it has two entries, so the length is checked where it is read.
 */
export type ZoneTable = Record<string, readonly number[]>;

export interface ViewerPlace {
  /** The zone's own last path segment, which is a city name in all but a handful of cases. */
  label: string;
  lon: number;
  lat: number;
}

/**
 * A readable name from an IANA zone.
 *
 * The last path segment, underscores out. `America/Argentina/Buenos_Aires` gives "Buenos Aires" and
 * `America/Indiana/Indianapolis` gives "Indianapolis", which is why it is the last segment rather than
 * the second: the middle one is an administrative grouping, not a place anybody says.
 */
export function zoneLabel(zone: string): string {
  const last = zone.split("/").pop() ?? zone;
  return last.replace(/_/g, " ");
}

/**
 * Where the reader's timezone points, or null when it cannot be resolved.
 *
 * Null rather than a guess, in three cases that all happen: the browser reports a zone the table does not
 * carry, `Intl` reports nothing at all, or it reports `UTC` - which is not a place, and is what a machine
 * with no configured zone says. A wrong city is worse than no line.
 */
export function viewerPlace(zones: ZoneTable, zone: string | undefined): ViewerPlace | null {
  if (!zone || zone === "UTC" || zone === "Etc/UTC" || zone === "Etc/GMT") return null;
  const at = zones[zone];
  if (!at || at.length < 2) return null;
  const lon = at[0]!;
  const lat = at[1]!;
  if (!Number.isFinite(lon) || !Number.isFinite(lat)) return null;
  return { label: zoneLabel(zone), lon, lat };
}

/** The reader's zone as the browser reports it, or undefined where `Intl` is unavailable. */
export function localZone(): string | undefined {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone;
  } catch {
    // Older engines throw rather than returning undefined. Either way there is nothing to say.
    return undefined;
  }
}

export interface Closest {
  quake: Quake;
  /** Great-circle kilometres from the zone's coordinate to the epicentre. */
  km: number;
  /**
   * Seconds until the first shaking would have reached that point, or null when it is too far.
   *
   * Null past `MAX_KM`, which is `arrival.ts`'s own backstop and exists for a real reason: a straight
   * line at crustal speed stops describing the path once the wave is diving through the mantle, so a
   * number quoted for a distant event would be arithmetic rather than seismology. Most days the closest
   * event is far away, so this is null far more often than not, and the distance still stands on its own.
   */
  p: number | null;
  gap: number | null;
}

/**
 * The nearest event in the window to a point, or null when the window is empty.
 *
 * A full pass over the buffer, run against the same `matches` the map draws with, so the event named is
 * one that is actually on screen. Ties go to the first seen, which at equal distance is arbitrary and
 * unimportant.
 */
export function closestTo(
  store: Store, at: { lon: number; lat: number }, filters: Filters, now: number, until = now,
): Closest | null {
  let best: Closest | null = null;
  store.forEach((quake) => {
    if (!matches(quake, filters, now)) return;
    /*
     * Not past the moment on screen.
     *
     * Every other note in this block describes the window, and that is fine for an aggregate: the
     * headline says "held" with a clock beside it, so a reader knows they are looking at part of a whole.
     * This line does not describe an aggregate - it names one event - and with the cursor parked it named
     * whichever event was nearest across the whole window, including ones the globe had not drawn yet.
     * Being told the closest thing to your city while looking at a map that does not show it is the same
     * defect the ranking had on an empty screen.
     */
    if (quake.primary.time > until) return;
    const km = distanceKm(at.lon, at.lat, quake.primary.lon, quake.primary.lat);
    if (best !== null && km >= best.km) return;
    const path = km <= MAX_KM ? pathKm(km, quake.primary.depthKm) : null;
    best = {
      quake,
      km,
      p: path === null ? null : path / P_WAVE_KM_PER_S,
      gap: path === null ? null : path / S_WAVE_KM_PER_S - path / P_WAVE_KM_PER_S,
    };
  });
  return best;
}

/** Its own chunk on first use: 13kB of table has no business in the bundle that paints the first frame. */
export async function loadZones(): Promise<ZoneTable> {
  const module = await import("../data/zones.json");
  return module.default as ZoneTable;
}
