import { distanceKm } from "../geo/sphere";
import { P_WAVE_KM_PER_S, S_WAVE_KM_PER_S } from "../geo/waves";
import { MAX_KM, pathKm } from "./arrival";
import { matches } from "../data/filter";
import type { Store } from "../data/store";
import type { Filters, Quake } from "../data/types";

/*
 * The nearest event to where the reader is, roughly.
 *
 * Nothing is asked and nothing leaves the browser. The only input is the timezone, which any page can read
 * without a prompt, looked up in a table that ships with the bundle.
 *
 * Name the city, never the reader. A timezone is a region - `Asia/Shanghai` covers all of China - so "310 km
 * from you" would be a confident claim about a person built from a reference point.
 */

/** `[lon, lat]`, as generated by `tools/make-zones.mjs` from tzdb. Typed as a plain array rather than a
 * pair, because that is what parsed JSON is: the length is checked where it is read. */
export type ZoneTable = Record<string, readonly number[]>;

export interface ViewerPlace {
  /** The zone's own last path segment, which is a city name in all but a handful of cases. */
  label: string;
  lon: number;
  lat: number;
}

/**
 * A readable name from an IANA zone: the last path segment, underscores out. The last rather than the
 * second, because `America/Indiana/Indianapolis` has an administrative grouping in the middle.
 */
export function zoneLabel(zone: string): string {
  const last = zone.split("/").pop() ?? zone;
  return last.replace(/_/g, " ");
}

/**
 * Where the reader's timezone points, or null when it cannot be resolved. Null rather than a guess, in three
 * cases that all happen: the table does not carry the zone, `Intl` reports nothing, or it reports `UTC`,
 * which is not a place. A wrong city is worse than no line.
 */
export function viewerPlace(zones: ZoneTable, zone: string | undefined): ViewerPlace | null {
  if (!zone || zone === "UTC" || zone === "Etc/UTC" || zone === "Etc/GMT") return null;
  const at = zones[zone];
  if (!at || at.length < 2) return null;
  const lon = at[0]!;
  const lat = at[1]!;
  if (!Number.isFinite(lon) || !Number.isFinite(lat)) return null;
  return { label: zoneLabel(zone), lon, lat };
}

/** The reader's zone as the browser reports it, or undefined where `Intl` is unavailable. */
export function localZone(): string | undefined {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone;
  } catch {
    // Older engines throw rather than returning undefined. Either way there is nothing to say.
    return undefined;
  }
}

export interface Closest {
  quake: Quake;
  /** Great-circle kilometres from the zone's coordinate to the epicentre. */
  km: number;
  /** Seconds until the first shaking would have reached that point, or null past `MAX_KM`. A straight line
   * at crustal speed stops describing the path once the wave dives through the mantle. Most days the closest
   * event is far away, so this is null more often than not and the distance stands on its own. */
  p: number | null;
  gap: number | null;
}

/**
 * The nearest event in the window to a point, or null. A full pass over the buffer, run against the same
 * `matches` the map draws with, so the event named is one that is actually on screen.
 */
export function closestTo(
  store: Store, at: { lon: number; lat: number }, filters: Filters, now: number, until = now,
): Closest | null {
  let best: Closest | null = null;
  store.forEach((quake) => {
    if (!matches(quake, filters, now)) return;
    /*
     * Not past the moment on screen. Every other line in this block describes an aggregate, where the
     * headline says "held" with a clock beside it; this one names a single event, and with the cursor parked
     * it named whichever was nearest across the whole window, including ones the globe had not drawn yet.
     */
    if (quake.primary.time > until) return;
    const km = distanceKm(at.lon, at.lat, quake.primary.lon, quake.primary.lat);
    if (best !== null && km >= best.km) return;
    const path = km <= MAX_KM ? pathKm(km, quake.primary.depthKm) : null;
    best = {
      quake,
      km,
      p: path === null ? null : path / P_WAVE_KM_PER_S,
      gap: path === null ? null : path / S_WAVE_KM_PER_S - path / P_WAVE_KM_PER_S,
    };
  });
  return best;
}

/** Its own chunk on first use: 13kB of table has no business in the bundle that paints the first frame. */
export async function loadZones(): Promise<ZoneTable> {
  const module = await import("../data/zones.json");
  return module.default as ZoneTable;
}
