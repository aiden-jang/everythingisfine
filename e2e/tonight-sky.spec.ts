import { expect, test } from "@playwright/test";
import { installFeeds, openStories, revealStoryTools, selectScene } from "./feeds";

test("Tonight’s Sky follows the selected city and time on the same globe", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.clock.setFixedTime(new Date("2026-11-06T18:00:00Z"));
  await installFeeds(page, { presentation: "fresh" });
  await page.route("https://celestrak.org/NORAD/elements/gp.php?**", (route) => route.abort());
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => {
    if (message.type() === "error" && /shader|WebGLProgram/i.test(message.text()))
      errors.push(message.text());
  });
  await page.goto("/");
  const canvas = page.locator("#globe-view canvas");
  const original = await canvas.elementHandle();
  await selectScene(page, "After Dark");
  await revealStoryTools(page);
  const open = page.getByRole("button", { name: "Tonight’s Sky", exact: true });
  await open.click();
  const sky = page.getByRole("region", { name: "Tonight’s Sky" });
  const city = sky.getByRole("combobox", { name: "City" });
  await city.selectOption("Tokyo");
  const targets = sky.getByRole("list", { name: "Above the horizon" });
  const offered = await targets.getByRole("button").first().getAttribute("aria-label");
  const target = offered!.replace("Find ", "");
  const invitation = sky.getByRole("region", { name: "Start observing" });
  await expect(invitation).toContainText("Tokyo’s horizon");
  await expect(invitation.getByRole("heading")).toHaveText(/^Look (north|east|south|west)/);
  await expect(sky.locator(".tonight-below")).not.toHaveAttribute("open");
  await expect(sky.getByRole("button", { name: /below horizon/ })).toHaveCount(0);
  const projection = page.getByRole("group", { name: "Sky reference projection" });
  await projection.getByRole("button", { name: "Orbit" }).click();
  await expect(projection.getByRole("button", { name: "Orbit" })).toHaveAttribute("aria-pressed", "true");
  await invitation
    .getByRole("button", { name: `Find ${target === "Moon" ? "the Moon" : target}`, exact: true })
    .click();
  await expect(invitation).toHaveCount(0);
  await expect(projection.getByRole("button", { name: "Local sky" })).toHaveAttribute("aria-pressed", "true");
  const horizon = page.getByRole("group", { name: "Local horizon" });
  await expect(horizon).toContainText("Tokyo · Local horizon");
  await horizon.getByRole("button", { name: "Look east" }).click();
  await expect(horizon).toContainText("Facing E · 90°");
  const slider = sky.getByRole("slider", { name: "City local time" });
  const time = sky.locator("time");
  await slider.press("Home");
  const sunset = await time.getAttribute("datetime");
  const sunsetReadings = await targets.innerText();
  await slider.press("End");
  const sunrise = await time.getAttribute("datetime");
  expect(Date.parse(sunrise!) - Date.parse(sunset!)).toBeGreaterThan(10 * 3_600_000);
  await expect(targets).not.toHaveText(sunsetReadings, { useInnerText: true });
  await expect(horizon).toContainText("Facing E · 90°");
  await projection.getByRole("button", { name: "Orbit" }).click();
  await expect(horizon).toContainText("Tokyo · Orbit");
  await expect(horizon.locator(".sky-reference-marker")).toBeVisible();
  await expect(time).toHaveAttribute("datetime", sunrise!);
  await projection.getByRole("button", { name: "Local sky" }).click();
  await expect(horizon).toContainText("Facing E · 90°");
  await expect(time).toHaveAttribute("datetime", sunrise!);
  const sunriseReadings = await targets.innerText();
  await sky.getByRole("button", { name: "Meteor Nights", exact: true }).click();
  const linkedMeteor = page.getByRole("region", { name: "Meteor Nights" });
  await linkedMeteor.getByRole("combobox", { name: "Shower" }).selectOption("2026-12-13");
  await linkedMeteor.getByRole("button", { name: "Jump to a dark window" }).click();
  await horizon.getByRole("button", { name: "Look west" }).click();
  await expect(horizon).toContainText("Facing W · 270°");
  await linkedMeteor.getByRole("button", { name: "Sky view", exact: true }).click();
  await expect(city).toHaveValue("Tokyo");
  await expect(time).toHaveAttribute("datetime", sunrise!);
  await expect(targets).toHaveText(sunriseReadings, { useInnerText: true });
  await expect(horizon).toContainText("Facing E · 90°");
  await expect(horizon.locator("[data-radiant-arc]")).toHaveCount(0);
  await sky.getByRole("button", { name: "Meteor Nights", exact: true }).click();
  await linkedMeteor.getByRole("combobox", { name: "City" }).selectOption("London");
  await linkedMeteor.getByRole("button", { name: "Sky view", exact: true }).click();
  await expect(city).toHaveValue("London");
  await expect(horizon).toContainText("London · Local horizon");
  await expect(time).not.toHaveAttribute("datetime", sunrise!);
  await city.selectOption("Tokyo");
  await slider.press("End");
  await horizon.getByRole("button", { name: "Look east" }).click();
  expect(await canvas.evaluate((element, prior) => element === prior, original)).toBe(true);
  await page.setViewportSize({ width: 812, height: 375 });
  await expect(slider).toBeInViewport({ ratio: 1 });
  await expect(page.getByRole("link", { name: "aiden jang", exact: true })).toBeInViewport();
  await page.keyboard.press("Escape");
  await expect(open).toBeFocused();
  await openStories(page);
  await expect(page.getByRole("button", { name: "Sun Watch", exact: true })).toBeVisible();
  await open.click();
  await expect(city).toHaveValue("Tokyo");
  await page.keyboard.press("Escape");
  const meteorButton = page.getByRole("button", { name: "Meteor Nights", exact: true });
  await meteorButton.click();
  const meteor = page.getByRole("region", { name: "Meteor Nights" });
  await expect(meteor.getByRole("combobox", { name: "City" })).toHaveValue("Tokyo");
  await expect(horizon).toContainText("Facing E · 90°");
  await meteor.getByRole("combobox", { name: "Shower" }).selectOption("2026-12-13");
  await meteor.getByRole("button", { name: "Jump to a dark window" }).click();
  await expect(meteor.getByText(/Dark sky and Moon below the horizon/)).toBeVisible();
  await expect(horizon.locator("[data-radiant-arc]")).toHaveAttribute("d", /^M/);
  await meteor.getByRole("button", { name: "Sky view", exact: true }).click();
  await expect(page.getByRole("region", { name: "Tonight’s Sky", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Sky view", exact: true })).toHaveAttribute(
    "aria-pressed",
    "true",
  );
  await page.keyboard.press("Escape");
  await expect(meteorButton).toBeFocused();
  await openStories(page);
  await page.getByRole("button", { name: "Orbital Pass", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "City" })).toHaveValue("Tokyo");
  expect(await canvas.evaluate((element, prior) => element === prior, original)).toBe(true);
  expect(errors).toEqual([]);
});

test("Moonfall reuses the sky canvas and restores the city, time, and bearing", async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.clock.setFixedTime(new Date("2026-11-06T18:00:00Z"));
  await installFeeds(page, { presentation: "fresh" });
  const survey = /\/a\/taurus-littrow-[^/]+\.bin$/;
  await page.route(survey, (route) => route.abort(), { times: 1 });
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/");
  await selectScene(page, "After Dark");
  await revealStoryTools(page);
  await page.getByRole("button", { name: "Tonight’s Sky", exact: true }).click();
  const sky = page.getByRole("region", { name: "Tonight’s Sky" });
  await sky.getByRole("combobox", { name: "City" }).selectOption("Tokyo");
  await sky.getByRole("slider", { name: "City local time" }).press("End");
  const time = await sky.locator("time").getAttribute("datetime");
  const horizon = page.getByRole("group", { name: "Local horizon" });
  await horizon.getByRole("button", { name: "Look east" }).click();
  const canvas = page.locator("#globe-view canvas");
  const original = await canvas.elementHandle();
  const open = sky.locator("#open-moonfall");
  await open.click();
  const moonfall = page.getByRole("region", { name: "Moonfall" });
  await expect(moonfall.getByRole("button", { name: "Back to Tonight’s Sky" })).toBeFocused();
  await moonfall.getByRole("button", { name: "Retry survey" }).click();
  const valley = page.getByRole("group", { name: "Lunar view" });
  await expect(valley).toContainText("Taurus–Littrow Valley");
  const route = moonfall.getByRole("combobox", { name: "Rover traverse" });
  const stops = moonfall.getByRole("combobox", { name: "Geology stop" });
  const distance = moonfall.getByRole("slider", { name: "Mapped distance" });
  await expect(route.locator("option")).toHaveCount(3);
  await route.selectOption("1");
  await stops.selectOption({ label: "Shorty Crater" });
  const shorty = Number(await distance.inputValue());
  const stop = await stops.inputValue();
  expect(shorty).toBeGreaterThan(0);
  expect(shorty).toBeLessThan(250);
  await moonfall.getByRole("button", { name: "Landing map" }).click();
  await expect(valley).toContainText("Taurus–Littrow landing map");
  await expect(distance).toHaveValue(String(shorty));
  await expect(stops).toHaveValue(stop);
  await moonfall.getByRole("button", { name: "Terrain" }).click();
  await expect(valley).toContainText("Taurus–Littrow Valley");
  await distance.press("End");
  await expect(distance).toHaveValue("250");
  await moonfall.getByRole("button", { name: "Replay" }).click();
  await expect.poll(async () => Number(await distance.inputValue())).toBeLessThan(250);
  await moonfall.getByRole("button", { name: "Pause" }).click();
  await page.setViewportSize({ width: 812, height: 375 });
  await expect(distance).toBeInViewport();
  expect(await canvas.evaluate((element, prior) => element === prior, original)).toBe(true);
  await page.keyboard.press("Escape");
  await expect(open).toBeFocused();
  await expect(sky.getByRole("combobox", { name: "City" })).toHaveValue("Tokyo");
  await expect(sky.locator("time")).toHaveAttribute("datetime", time!);
  await expect(horizon).toContainText("Facing E · 90°");
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await open.click();
  await expect(valley).toContainText("Lunar approach");
  await expect(moonfall.getByRole("slider", { name: "Mapped distance" })).toHaveCount(0);
  await moonfall.getByRole("button", { name: "Skip descent" }).click();
  await expect(valley).toContainText("Taurus–Littrow Valley");
  await expect(moonfall.getByRole("slider", { name: "Mapped distance" })).toBeVisible();
  expect(errors).toEqual([]);
});

test("Moonfall returns to the Earth map with the same sky time", async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.clock.setFixedTime(new Date("2026-11-06T18:00:00Z"));
  await installFeeds(page, { presentation: "fresh" });
  await page.goto("/");
  await selectScene(page, "After Dark");
  await revealStoryTools(page);
  await page.getByRole("button", { name: "Tonight’s Sky", exact: true }).click();
  const sky = page.getByRole("region", { name: "Tonight’s Sky" });
  const projection = page.getByRole("group", { name: "Sky reference projection" });
  await sky.getByRole("slider", { name: "City local time" }).press("Home");
  const at = await sky.locator("time").getAttribute("datetime");
  await projection.getByRole("button", { name: "Map" }).click();
  await sky.locator("#open-moonfall").click();
  const moon = page.getByRole("region", { name: "Moonfall", exact: true });
  await moon.getByRole("combobox", { name: "Geology stop" }).selectOption({ label: "Steno Crater" });
  await moon.getByRole("button", { name: "Keep this stop" }).click();
  await expect(moon.getByRole("button", { name: "Stop kept" })).toBeDisabled();
  await moon.getByRole("button", { name: "Back to Tonight’s Sky" }).click();
  await expect(sky.locator("time")).toHaveAttribute("datetime", at!);
  await expect(projection.getByRole("button", { name: "Map" })).toHaveAttribute("aria-pressed", "true");
  await sky.locator("#open-moonfall").click();
  await expect(moon.getByRole("combobox", { name: "Geology stop" })).toBeVisible();
  await page.goBack();
  await expect(sky.locator("time")).toHaveAttribute("datetime", at!);
  await expect(projection.getByRole("button", { name: "Map" })).toHaveAttribute("aria-pressed", "true");
});
